import type { Scan, SourceFile } from "./types";
import { excluded, supported } from "./scanner";
export const native = "__TAURI_INTERNALS__" in window;
export async function invoke<T>(
  command: string,
  args?: Record<string, unknown>,
): Promise<T> {
  const api = await import("@tauri-apps/api/core");
  return api.invoke<T>(command, args);
}
export async function pickNative(): Promise<string | null> {
  const { open } = await import("@tauri-apps/plugin-dialog");
  const selected = await open({
    directory: true,
    multiple: false,
    title: "Open a repository",
  });
  return typeof selected === "string" ? selected : null;
}
export function scanInWorker(
  files: SourceFile[],
  name: string,
  path: string,
): Promise<Scan> {
  return new Promise((resolve, reject) => {
    const worker = new Worker(new URL("./scan.worker.ts", import.meta.url), {
      type: "module",
    });
    worker.onmessage = (e) => {
      worker.terminate();
      e.data.error ? reject(new Error(e.data.error)) : resolve(e.data.result);
    };
    worker.onerror = () => {
      worker.terminate();
      reject(new Error("Scanner failed. Try a smaller folder."));
    };
    worker.postMessage({ files, name, path });
  });
}
export async function readFiles(
  files: FileList,
  onProgress: (n: number) => void,
): Promise<SourceFile[]> {
  const result: SourceFile[] = [];
  let count = 0;
  for (const file of Array.from(files)) {
    const path =
      file.webkitRelativePath.split("/").slice(1).join("/") || file.name;
    if (excluded.test(path) || !supported.test(path) || file.size > 2_000_000)
      continue;
    result.push({ path, content: await file.text() });
    if (++count % 50 === 0) onProgress(count);
  }
  return result;
}
export function download(content: string, name: string, type = "text/plain") {
  const url = URL.createObjectURL(new Blob([content], { type }));
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
export function exampleText(scan: Scan): string {
  const groups = new Map<string, string[]>();
  for (const v of scan.variables.filter((v) => v.status !== "dead")) {
    const section = v.services[0] || "shared";
    if (!groups.has(section)) groups.set(section, []);
    groups.get(section)!.push(`${v.name}=`);
  }
  return (
    "# Generated by Env Reaper. Values intentionally omitted.\n# Populate credentials locally; never commit real secrets.\n\n" +
    [...groups]
      .map(
        ([group, lines]) =>
          `# ${group.toUpperCase()}\n${lines.sort().join("\n")}`,
      )
      .join("\n\n") +
    "\n"
  );
}
